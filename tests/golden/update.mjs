/**
 * Rewrites tests/golden/rgb-lib-wasm-1.0.0-beta.4.golden.mjs from the current
 * code: `npm run golden:update`. Run it only when a change of public results
 * is intended, and review the diff.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { toSource } from '../fixtures/source.mjs';
import { collectCases, loadFixtures, runCase } from './runner.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const mods = await loadFixtures();
const golden = {};
for (const c of collectCases(mods)) golden[c.name] = await runCase(mods, c);

const out = path.join(here, 'rgb-lib-wasm-1.0.0-beta.4.golden.mjs');
fs.writeFileSync(
  out,
  `// Golden public results of RgbLibWeb for every fixture case.
// Generated by \`npm run golden:update\` from the current code; review diffs.
export const golden = ${toSource(golden)};
`
);
console.log(
  `${Object.keys(golden).length} golden cases → ${path.relative(process.cwd(), out)}`
);
